/**
 * Compile a policy into native static rules, as a second layer under the hooks:
 *
 *   codex   ->  .codex/rules/polyfence.rules   (Starlark prefix_rule, see `codex execpolicy check`)
 *   gemini  ->  .gemini/policies/polyfence.toml (Gemini CLI policy engine)
 *
 * Only rules that translate faithfully are emitted. Everything else stays
 * hook-enforced and is listed in a comment so nothing is silently dropped.
 */
import os from 'node:os';
import { commandGlobSource, isRegexLiteral, pathGlobSource } from './patterns.js';
import type { Policy, Rule, ToolKind } from './types.js';

const arr = <T>(v: T | T[] | undefined): T[] => (v === undefined ? [] : Array.isArray(v) ? v : [v]);

const HEADER = (source: string | undefined, comment: string) =>
  `${comment} Generated by polyfence from ${source ?? 'built-in presets'}.\n` +
  `${comment} Do not edit by hand: change the policy and run \`polyfence install\` again.\n`;

function reasonText(rule: Rule): string {
  return `polyfence[${rule.id}]: ${rule.reason ?? (rule.decision === 'deny' ? 'blocked by policy' : 'needs approval')}`;
}

/** `git push *` -> ['git', 'push']; null if the glob is not a plain token prefix. */
export function literalPrefix(pattern: string): string[] | null {
  if (pattern.startsWith('!') || isRegexLiteral(pattern)) return null;
  const tokens = pattern.trim().split(/\s+/);
  if (tokens[tokens.length - 1] === '*') tokens.pop();
  if (!tokens.length || tokens.some((t) => /[*?]/.test(t))) return null;
  return tokens;
}

function appliesTo(rule: Rule, agent: string): boolean {
  return !rule.match.agent || arr(rule.match.agent).includes(agent as never);
}

const onlyKeys = (rule: Rule, keys: string[]) => Object.keys(rule.match).every((k) => keys.includes(k));

// ---- Codex ------------------------------------------------------------------

export function compileCodex(policy: Policy): string {
  let out = HEADER(policy.source, '#') + '\n';
  const skipped: string[] = [];
  for (const rule of policy.rules) {
    if (!appliesTo(rule, 'codex') || rule.decision === 'allow') continue;
    const patterns = arr(rule.match.command);
    const prefixes = patterns.map(literalPrefix);
    // A negated pattern narrows the rule; prefix rules can't express that.
    if (!patterns.length || !onlyKeys(rule, ['command', 'tool', 'agent']) || patterns.some((p) => p.startsWith('!'))) {
      skipped.push(rule.id);
      continue;
    }
    if (prefixes.some((p) => !p)) skipped.push(`${rule.id} (partly)`);
    for (const prefix of prefixes.filter(Boolean) as string[][]) {
      out +=
        `prefix_rule(\n` +
        `    pattern = ${JSON.stringify(prefix).replace(/","/g, '", "')},\n` +
        `    decision = "${rule.decision === 'deny' ? 'forbidden' : 'prompt'}",\n` +
        `    justification = ${JSON.stringify(reasonText(rule))},\n` +
        `)\n\n`;
    }
  }
  if (skipped.length) out += `# Enforced by the polyfence hook only (not expressible as prefix rules):\n#   ${skipped.join(', ')}\n`;
  return out;
}

// ---- Gemini -----------------------------------------------------------------

const GEMINI_TOOLS: Partial<Record<ToolKind, string[]>> = {
  read: ['read_file', 'read_many_files'],
  write: ['write_file'],
  edit: ['replace'],
  fetch: ['web_fetch', 'google_web_search'],
};

function tomlString(s: string): string {
  if (!s.includes("'") && !/[\n\r]/.test(s)) return `'${s}'`;
  return JSON.stringify(s);
}

/**
 * Gemini matches `commandRegex` against the JSON-encoded args right after
 * `"command":"`, so the start is already anchored and `$` must become "end of
 * the JSON string".
 */
function toArgsRegex(source: string): string {
  let out = '';
  let inClass = false;
  for (let i = 0; i < source.length; i++) {
    const c = source[i];
    if (c === '\\') {
      out += c + (source[i + 1] ?? '');
      i++;
      continue;
    }
    if (c === '[') inClass = true;
    else if (c === ']') inClass = false;
    if (!inClass && c === '^' && i === 0) continue;
    if (!inClass && c === '$') {
      out += '(?=")';
      continue;
    }
    out += c;
  }
  return out;
}

function commandSource(pattern: string): string | null {
  const m = /^\/(.+)\/([a-z]*)$/s.exec(pattern);
  if (m) return m[2].replace(/[gsu]/g, '') ? null : toArgsRegex(m[1]);
  return toArgsRegex(commandGlobSource(pattern) + '$');
}

function pathValueSource(glob: string): string {
  let g = glob.startsWith('./') ? glob.slice(2) : glob;
  if (g.startsWith('~/')) g = os.homedir() + g.slice(1);
  const body = pathGlobSource(g).replace(/\[\^\/\]/g, '[^/"]').replace(/\.\*/g, '[^"]*');
  return g.startsWith('/') ? body : `(?:[^"]*/)?${body}`;
}

function pathArgsPattern(patterns: string[]): string | null {
  if (patterns.some(isRegexLiteral) || patterns.some((p) => p.startsWith('!/'))) return null;
  const pos = patterns.filter((p) => !p.startsWith('!')).map(pathValueSource);
  const neg = patterns.filter((p) => p.startsWith('!')).map((p) => pathValueSource(p.slice(1)));
  const lookahead = neg.length ? `(?!(?:${neg.join('|')})")` : '';
  return `"(?:file_path|absolute_path|path)":"${lookahead}(?:${pos.join('|')})"`;
}

interface GeminiRule {
  toolName?: string | string[];
  commandPrefix?: string[];
  commandRegex?: string;
  argsPattern?: string;
}

function geminiRulesFor(rule: Rule): GeminiRule[] | null {
  const m = rule.match;
  if (m.url || m.rawTool || m.outsideWorkspace !== undefined) return null;
  const cmd = arr(m.command);
  const line = arr(m.commandLine);
  if (cmd.length || line.length) {
    if (m.path || m.writePath) return null;
    if (cmd.some((p) => p.startsWith('!')) || line.some((p) => p.startsWith('!'))) return null;
    const out: GeminiRule[] = [];
    const prefixes = cmd.map(literalPrefix);
    const simple = prefixes.filter(Boolean) as string[][];
    if (simple.length) out.push({ commandPrefix: simple.map((p) => p.join(' ')) });
    for (let i = 0; i < cmd.length; i++) {
      if (prefixes[i]) continue;
      const src = commandSource(cmd[i]);
      if (src === null) return null;
      out.push({ commandRegex: src });
    }
    for (const p of line) {
      const src = commandSource(p);
      if (src === null) return null;
      out.push({ commandRegex: `.*${src.replace(/^\.\*/, '')}` });
    }
    return out;
  }
  const paths = m.path ? arr(m.path) : m.writePath ? arr(m.writePath) : [];
  const kinds = arr(m.tool).filter((t) => t !== 'any') as ToolKind[];
  const toolKinds: ToolKind[] = kinds.length ? kinds : m.writePath ? ['write', 'edit'] : ['read', 'write', 'edit'];
  const toolNames = toolKinds.flatMap((k) => GEMINI_TOOLS[k] ?? []);
  if (!toolNames.length) return null;
  if (!paths.length) return [{ toolName: toolNames }];
  const argsPattern = pathArgsPattern(paths);
  return argsPattern ? [{ toolName: toolNames, argsPattern }] : null;
}

export function compileGemini(policy: Policy): string {
  let out = HEADER(policy.source, '#') + '\n';
  const skipped: string[] = [];
  for (const rule of policy.rules) {
    if (!appliesTo(rule, 'gemini') || rule.decision === 'allow') continue;
    const native = geminiRulesFor(rule);
    if (!native) {
      skipped.push(rule.id);
      continue;
    }
    for (const r of native) {
      out += `# ${rule.id}\n[[rule]]\n`;
      if (r.toolName) {
        out += Array.isArray(r.toolName)
          ? `toolName = [${r.toolName.map((t) => `"${t}"`).join(', ')}]\n`
          : `toolName = "${r.toolName}"\n`;
      }
      if (r.commandPrefix) out += `commandPrefix = [${r.commandPrefix.map(tomlString).join(', ')}]\n`;
      if (r.commandRegex) out += `commandRegex = ${tomlString(r.commandRegex)}\n`;
      if (r.argsPattern) out += `argsPattern = ${tomlString(r.argsPattern)}\n`;
      out += `decision = "${rule.decision === 'deny' ? 'deny' : 'ask_user'}"\n`;
      out += `priority = ${rule.decision === 'deny' ? 950 : 900}\n`;
      if (rule.decision === 'deny') out += `denyMessage = ${tomlString(reasonText(rule))}\n`;
      out += '\n';
    }
  }
  if (skipped.length) out += `# Enforced by the polyfence hook only (not expressible as policy rules):\n#   ${skipped.join(', ')}\n`;
  return out;
}
